//....Optimal Bucket Soln...

class Solution {
public:
    int singleNumber(vector<int>& nums) {
        int n=nums.size();
        int ones=0;              // ...Single Appearance ...
        int twos=0;              //...Twice Appearance...
        //...Traverse through the Array
        for(int i=0;i<n;i++){
            ones=(ones ^ nums[i]) & ~twos;     //...Get into ones only if not in Twos...
            twos=(twos ^ nums[i]) & ~ones;     //...Get into twos iff not in ones ...
        }
        return ones;
    }
};